

# String (text)
name = "Harshini"
print("Name:", name)
print("Type:", type(name))

# Integer (whole number)
age = 21
print("Age:", age)
print("Type:", type(age))

# Float (decimal number)
height = 5.4
print("Height:", height)
print("Type:", type(height))

# Boolean (True or False)
is_student = True
print("Is Student:", is_student)
print("Type:", type(is_student))